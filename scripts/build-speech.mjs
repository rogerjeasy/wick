#!/usr/bin/env node
/**
 * Writes the edge's copy of what is read aloud.
 *
 * "Read to me" (packages/contracts/src/speech.ts): the edge answers her
 * asking with a reading of the card on her screen, and what is read —
 * `speechTextOf`, the voices, where a reading is kept — is the contract's.
 * The edge Lambdas (services/edge-device/lambda) are plain .mjs, zipped as
 * they are (infra/pairing.tf): they cannot import TypeScript. So, exactly as
 * for the phrasebook (scripts/build-phrasebook.mjs), the contract's module
 * is bundled, whole and with no dependencies, into one file beside them:
 *
 *   npm run speech:build
 *
 * The file is committed. It is generated, never edited and never copied by
 * hand: the edge's speech.test.ts fails unless generating it again gives
 * exactly the bytes checked in, so the copy cannot drift from its source.
 *
 * A generator of its own, beside the phrasebook's and not inside it: the two
 * copies have different sources and different owners, and one changing must
 * not rewrite the other.
 *
 * Importing this file builds nothing; running it does.
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** What it is generated from: this file and everything it imports (types only, so: this file). */
export const SPEECH_SOURCE = 'packages/contracts/src/speech.ts';
export const SPEECH_FILE = path.join(ROOT, 'services', 'edge-device', 'lambda', 'speech.generated.mjs');

const HEADER = `/**
 * GENERATED by \`npm run speech:build\` — do not edit.
 *
 * What is read aloud when she asks ("Read to me") as the edge Lambdas use
 * it: a copy of packages/contracts/src/speech.ts, bundled into one file with
 * no dependencies, because a plain .mjs Lambda cannot import TypeScript.
 * Change the source and run the command again; __tests__/speech.test.ts
 * holds this file to it, byte for byte.
 */`;

/** The generated module, whole. The same source gives the same text. */
export async function renderSpeechModule() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [SPEECH_SOURCE],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    // The Lambda runtime (nodejs22.x): nothing is rewritten for an older one.
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: HEADER },
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

export async function main() {
  writeFileSync(SPEECH_FILE, await renderSpeechModule());
  console.log(`wrote ${path.relative(ROOT, SPEECH_FILE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
