#!/usr/bin/env node
/**
 * Writes the libraries the project pages (docs/, served by GitHub Pages) use,
 * from the root devDependencies, into docs/assets/vendor/:
 *
 *   npm run pages:vendor
 *
 *   fonts.css + fonts/*.woff2   Atkinson Hyperlegible Next, self-hosted
 *                               (@fontsource-variable/atkinson-hyperlegible-next)
 *   icons.svg                   the Lucide icons the pages use, as one sprite of
 *                               <symbol id="…"> (lucide-static), for <use href>
 *   motion.js                   Motion's animate, inView and stagger, bundled by
 *                               esbuild into one ES module (motion)
 *   easings.css                 Open Props' easing curves (open-props)
 *   licenses/                   each library's licence, as it ships
 *
 * GitHub Pages has no build step, so the output is committed. It is
 * generated, never edited: change this file or the ICONS list and run it
 * again. scripts/__tests__/pages.test.ts fails if a page names an icon the
 * sprite does not hold.
 *
 * Importing this file writes nothing; running it does.
 */
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MODULES = path.join(ROOT, 'node_modules');
export const VENDOR_DIR = path.join(ROOT, 'docs', 'assets', 'vendor');
export const SPRITE_FILE = path.join(VENDOR_DIR, 'icons.svg');

/** Every Lucide icon a page uses, by its Lucide name; the sprite's ids are these names. */
export const ICONS = [
  // Pillars and features (docs/design/DESIGN.md §5 names the shared ones)
  'bell', 'message-square', 'activity', 'sunrise', 'send', 'message-circle-question', 'circle-pause',
  'clapperboard', 'flame', 'phone', 'clipboard-check', 'tv', 'languages', 'image', 'volume-2', 'eye',
  'calendar-clock', 'scroll-text',
  // Film controls
  'play', 'pause', 'volume-x', 'captions', 'maximize',
  // Navigation, links and the rest of the page
  'arrow-right', 'arrow-up-right', 'arrow-down', 'smartphone', 'code-xml', 'shield-check', 'lock', 'eye-off',
  'check', 'x', 'badge-check', 'flask-conical', 'file-text', 'book-open', 'map', 'house', 'users', 'gauge',
  'timer', 'memory-stick', 'zap', 'server', 'git-pull-request', 'package', 'heart', 'circle-help', 'door-open',
];

const LICENCE = (pkg, file = 'LICENSE') => path.join(MODULES, pkg, file);

function fonts() {
  const pkg = path.join(MODULES, '@fontsource-variable', 'atkinson-hyperlegible-next');
  const out = path.join(VENDOR_DIR, 'fonts');
  mkdirSync(out, { recursive: true });
  const css = ['index.css', 'wght-italic.css']
    .map((f) => readFileSync(path.join(pkg, f), 'utf8'))
    .join('\n')
    .replace(/url\(\.\/files\//g, 'url(./fonts/');
  for (const [, file] of css.matchAll(/url\(\.\/fonts\/([^)]+)\)/g)) copyFileSync(path.join(pkg, 'files', file), path.join(out, file));
  writeFileSync(path.join(VENDOR_DIR, 'fonts.css'), `/* Atkinson Hyperlegible Next, from @fontsource-variable/atkinson-hyperlegible-next (SIL OFL 1.1). Generated by scripts/pages-vendor.mjs. */\n${css}`);
}

/** One <symbol> per icon: the icon's own children, under its own viewBox. */
export function symbolOf(name, svg) {
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join('');
  return `<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`;
}

function icons() {
  const version = JSON.parse(readFileSync(path.join(MODULES, 'lucide-static', 'package.json'), 'utf8')).version;
  const symbols = ICONS.map((name) => symbolOf(name, readFileSync(path.join(MODULES, 'lucide-static', 'icons', `${name}.svg`), 'utf8')));
  writeFileSync(
    SPRITE_FILE,
    `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n` +
      `<!-- Lucide v${version} (ISC), from lucide-static. Generated by scripts/pages-vendor.mjs. -->\n` +
      symbols.join('\n') +
      '\n</svg>\n',
  );
}

async function motion() {
  await build({
    stdin: { contents: "export { animate, inView, stagger } from 'motion';", resolveDir: ROOT, loader: 'js' },
    bundle: true,
    format: 'esm',
    minify: true,
    target: 'es2020',
    legalComments: 'inline',
    banner: { js: '/* Motion (MIT), animate + inView + stagger, from the motion package. Generated by scripts/pages-vendor.mjs. */' },
    outfile: path.join(VENDOR_DIR, 'motion.js'),
  });
}

function easings() {
  writeFileSync(
    path.join(VENDOR_DIR, 'easings.css'),
    `/* Open Props easings (MIT), from open-props. Generated by scripts/pages-vendor.mjs. */\n${readFileSync(path.join(MODULES, 'open-props', 'easings.min.css'), 'utf8').trim()}\n`,
  );
}

function licences() {
  const out = path.join(VENDOR_DIR, 'licenses');
  mkdirSync(out, { recursive: true });
  copyFileSync(LICENCE('@fontsource-variable/atkinson-hyperlegible-next'), path.join(out, 'atkinson-hyperlegible-next.txt'));
  copyFileSync(LICENCE('lucide-static'), path.join(out, 'lucide.txt'));
  copyFileSync(LICENCE('motion', 'LICENSE.md'), path.join(out, 'motion.txt'));
  copyFileSync(LICENCE('open-props'), path.join(out, 'open-props.txt'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  rmSync(VENDOR_DIR, { recursive: true, force: true });
  mkdirSync(VENDOR_DIR, { recursive: true });
  fonts();
  icons();
  easings();
  licences();
  await motion();
  console.log(`pages:vendor → ${path.relative(ROOT, VENDOR_DIR)} (${ICONS.length} icons)`);
}
