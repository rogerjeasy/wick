/** The font's two subsets the page uses: upright only, as the television's own words are never italic. */
const FONT_FILES = ['atkinson-hyperlegible-next-latin-ext-wght-normal.woff2', 'atkinson-hyperlegible-next-latin-wght-normal.woff2'];

const packageDir = (name) => path.dirname(require.resolve(`${name}/package.json`));
const versionOf = (name) => JSON.parse(readFileSync(path.join(packageDir(name), 'package.json'), 'utf8')).version;

/** The @font-face rules, from the package's own stylesheet, with only the upright faces and the addresses made ours. */
function fontsCss() {
  const pkg = '@fontsource-variable/atkinson-hyperlegible-next';
  const source = readFileSync(path.join(packageDir(pkg), 'wght.css'), 'utf8');
  const faces = source
    .split(/(?=\/\* atkinson)/)
    .filter((block) => block.includes('@font-face') && FONT_FILES.some((file) => block.includes(file)))
    .map((block) => block.replace(/url\(\.\/files\//g, 'url(fonts/').trim());
  if (faces.length !== FONT_FILES.length) throw new Error(`expected ${FONT_FILES.length} faces in ${pkg}/wght.css, found ${faces.length}`);
  return `/*
 * GENERATED by \`npm run web:vendor\` — do not edit.
 * Atkinson Hyperlegible Next, from ${pkg}@${versionOf(pkg)}.
 * Licensed under the SIL Open Font License 1.1: fonts/OFL.txt.
 */
${faces.join('\n\n')}
`;
}

/** Lucide's drawing of each icon the page uses: element names and their attributes, nothing else. */
function iconNodes() {
  const nodes = JSON.parse(readFileSync(path.join(packageDir('lucide-static'), 'icon-nodes.json'), 'utf8'));
  return Object.fromEntries(
    Object.keys(ICONS).map((name) => {
      const drawn = nodes[name];
      if (!Array.isArray(drawn)) throw new Error(`lucide-static has no icon called ${name}`);
      return [name, drawn.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([key]) => key !== 'key'))])];
    }),
  );
}

function iconsJs() {
  const version = versionOf('lucide-static');
  return `/**
 * GENERATED by \`npm run web:vendor\` — do not edit.
 *
 * Lucide icons (lucide-static@${version}, ISC licence, https://lucide.dev),
 * the ones the browser television uses (scripts/web-vendor.mjs ICONS), as
 * path data. \`WickIcons.icon(name)\` builds one as an <svg> with
 * createElementNS — never innerHTML — drawn in the colour of the words
 * around it and hidden from screen readers: an icon always stands beside a
 * word or inside something that has a label of its own (DESIGN.md §5).
 */
var WickIcons = (function () {
  'use strict';
  var SVG = 'http://www.w3.org/2000/svg';
  var NODES = ${JSON.stringify(iconNodes())};
  function icon(name) {
    var nodes = NODES[name];
    if (!nodes) return null;
    var svg = document.createElementNS(SVG, 'svg');
    var attrs = { viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true', focusable: 'false', class: 'icon icon-' + name };
    for (var key in attrs) svg.setAttribute(key, attrs[key]);
    for (var i = 0; i < nodes.length; i++) {
      var part = document.createElementNS(SVG, nodes[i][0]);
      for (var name2 in nodes[i][1]) part.setAttribute(name2, nodes[i][1][name2]);
      svg.appendChild(part);
    }
    return svg;
  }
  return { icon: icon, names: Object.keys(NODES) };
})();
`;
}

async function motionJs() {
  const result = await build({
    absWorkingDir: ROOT,
    stdin: { contents: "export { animate } from 'motion/mini';", resolveDir: ROOT, loader: 'js', sourcefile: 'motion-entry.js' },
    bundle: true,
    format: 'iife',
    globalName: 'WickMotion',
    platform: 'browser',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    minify: true,
    banner: {
      js: `/**
 * GENERATED by \`npm run web:vendor\` — do not edit.
 *
 * Motion's \`animate\` (motion@${versionOf('motion')}, MIT licence,
 * https://motion.dev), from motion/mini, bundled as one classic script that
 * sets one global: \`WickMotion\`. The browser television animates a card in
 * and out with it (tv.js), and not at all when reduced motion is asked for.
 */`,
    },
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

/** open-props' easings and shadows, as the page uses them: one :root block, the dark values in place. */
async function openPropsCss() {
  const dir = packageDir('open-props');
  const load = async (file) => (await import(pathToFileURL(path.join(dir, 'src', file)).href)).default;
  const easing = await load('props.easing.js');
  const shadows = await load('props.shadows.js');
  const dark = (props) => {
    const out = {};
    for (const [key, value] of Object.entries(props)) {
      if (key.includes('-@media:')) continue;
      out[key] = props[`${key}-@media:dark`] ?? value;
    }
    return out;
  };
  const lines = Object.entries({ ...easing, ...dark(shadows) }).map(([key, value]) => `  ${key}: ${String(value).replace(/\s+/g, ' ').trim()};`);
  return `/*
 * GENERATED by \`npm run web:vendor\` — do not edit.
 * Easings and shadows from open-props@${versionOf('open-props')} (MIT licence, https://open-props.style),
 * with the dark-scheme values: the browser television is always dark.
 */
:root {
${lines.join('\n')}
}
`;
}

/** Every file vendor/ holds, by its path inside vendor/, with what it holds. The same packages give the same bytes. */
export async function vendorFiles() {
  const fontDir = path.join(packageDir('@fontsource-variable/atkinson-hyperlegible-next'), 'files');
  const files = new Map();
  for (const file of FONT_FILES) files.set(`fonts/${file}`, readFileSync(path.join(fontDir, file)));
  files.set('fonts/OFL.txt', readFileSync(path.join(packageDir('@fontsource-variable/atkinson-hyperlegible-next'), 'LICENSE')));
  files.set('fonts.css', fontsCss());
  files.set('icons.generated.js', iconsJs());
  files.set('motion.generated.js', await motionJs());
  files.set('open-props.css', await openPropsCss());
  return files;
}

/** What is in vendor/ now, the same shape as vendorFiles. */
export function vendoredNow(dir = VENDOR_DIR) {
  const found = new Map();
  const walk = (at) => {
    for (const name of readdirSync(at)) {
      const full = path.join(at, name);
      if (statSync(full).isDirectory()) walk(full);
      else found.set(path.relative(dir, full).split(path.sep).join('/'), readFileSync(full));
    }
  };
  walk(dir);
  return found;
}

export async function main() {
  const files = await vendorFiles();
  rmSync(VENDOR_DIR, { recursive: true, force: true });
  for (const [file, content] of files) {
    const target = path.join(VENDOR_DIR, file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`wrote ${[...files.keys()].map((f) => path.relative(ROOT, path.join(VENDOR_DIR, f))).join(', ')}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
