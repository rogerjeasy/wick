#!/usr/bin/env node
/**
 * Her television's icons, as pictures (docs/design/DESIGN.md §5).
 *
 * Lucide (`lucide-static`, ISC) is one set of line icons at one stroke
 * weight. The web draws them as SVG; her television cannot without a
 * native module (react-native-svg would need a Fire OS build of its own),
 * so each icon the television uses is rendered here, at build time, to a
 * PNG it shows with the core `Image`:
 *
 *   - in two colours: `ink` (#F4F1EA, words' colour, on the warm dark) and
 *     `ground` (#12100E, on the amber of a first button);
 *   - at two sizes: for 32dp (body text at the floor) and 40dp (larger
 *     text), each drawn at twice that in pixels, for a 1080p panel.
 *
 * It writes apps/tv-vega/assets/icons/<name>-<tone>-<dp>.png and
 * apps/tv-vega/src/icons/iconSources.generated.ts, which `require`s each so
 * the Vega bundler (and Metro on Fire OS) packs them. Run `npm run
 * tv:icons` after changing the list; commit what it writes.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);
const LUCIDE = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
const OUT = path.join(ROOT, 'apps/tv-vega/assets/icons');
const SOURCES = path.join(ROOT, 'apps/tv-vega/src/icons/iconSources.generated.ts');

/** What each icon means on her television, and Lucide's name for it (DESIGN.md §5). */
export const ICONS = {
  door: 'bell',
  note: 'message-square',
  read: 'volume-2',
  light: 'flame',
  mantel: 'image',
  seeing: 'eye',
  tour: 'circle-help',
  play: 'play',
  pause: 'pause',
  hold: 'phone',
};

/** calm-ui's palette (packages/vega-calm-ui/src/tokens.ts): the words' colour, and the ground's for an amber button. */
export const TONES = { ink: '#F4F1EA', ground: '#12100E' };

/** The sizes the television sets body text at: the floor, and with larger text on. */
export const SIZES_DP = [32, 40];
/** Pixels per dp on a 1080p panel (960x540dp). */
const SCALE = 2;

function svgFor(lucideName, colour) {
  const svg = readFileSync(path.join(LUCIDE, `${lucideName}.svg`), 'utf8');
  return svg.replace(/<!--[\s\S]*?-->/g, '').replace(/currentColor/g, colour);
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  const lines = [];
  for (const [meaning, lucideName] of Object.entries(ICONS)) {
    for (const [tone, colour] of Object.entries(TONES)) {
      for (const dp of SIZES_DP) {
        const px = dp * SCALE;
        const file = `${meaning}-${tone}-${dp}.png`;
        const png = await sharp(Buffer.from(svgFor(lucideName, colour)), { density: (72 * px) / 24 })
          .resize(px, px)
          .png({ compressionLevel: 9 })
          .toBuffer();
        writeFileSync(path.join(OUT, file), png);
        lines.push(`  '${meaning}-${tone}-${dp}': require('../../assets/icons/${file}') as ImageSourcePropType,`);
      }
    }
  }
  const source = `/**
 * Generated by \`npm run tv:icons\` (scripts/tv-icons.mjs) from lucide-static — do not edit.
 * Lucide icons are ISC-licensed (https://lucide.dev/license).
 */
import type { ImageSourcePropType } from '@amazon-devices/react-native-kepler';

/* eslint-disable @typescript-eslint/no-require-imports */
export const ICON_SOURCES: Readonly<Record<string, ImageSourcePropType>> = {
${lines.join('\n')}
};
/* eslint-enable @typescript-eslint/no-require-imports */
`;
  writeFileSync(SOURCES, source);
  console.log(`tv:icons — ${lines.length} pictures in ${path.relative(ROOT, OUT)}`);
}

await main();
