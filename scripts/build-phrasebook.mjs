#!/usr/bin/env node
/**
 * Writes the edge's copy of the phrasebook.
 *
 * The edge Lambdas (services/edge-device/lambda) are plain .mjs, zipped as
 * they are (infra/pairing.tf): they cannot import TypeScript, and nothing
 * outside that directory is in the zip. The phrasebook is TypeScript in
 * packages/contracts/src/phrasebook. So it is bundled, whole and with no
 * dependencies, into one file beside the Lambdas that use it:
 *
 *   npm run phrasebook:build
 *
 * The file is committed. It is generated, never edited: the edge's
 * phrasebookCoverage.test.ts fails unless generating it again gives exactly
 * the bytes checked in, so the copy cannot drift from its source.
 *
 * Importing this file builds nothing; running it does.
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** What it is generated from: this file and everything it imports. */
export const PHRASEBOOK_SOURCE = 'packages/contracts/src/phrasebook/index.ts';
export const PHRASEBOOK_FILE = path.join(ROOT, 'services', 'edge-device', 'lambda', 'phrasebook.generated.mjs');

const HEADER = `/**
 * GENERATED by \`npm run phrasebook:build\` — do not edit.
 *
 * The phrasebook — everything Wick itself says to the resident, in her
 * language — as the edge Lambdas use it: a copy of
 * packages/contracts/src/phrasebook (index.ts, engine.ts, es.ts), bundled
 * into one file with no dependencies, because a plain .mjs Lambda cannot
 * import TypeScript. Change the source and run the command again;
 * __tests__/phrasebookCoverage.test.ts holds this file to it, byte for byte.
 */`;

/** The generated module, whole. The same source gives the same text. */
export async function renderPhrasebookModule() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [PHRASEBOOK_SOURCE],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    // The Lambda runtime (nodejs22.x): nothing is rewritten for an older one.
    target: 'es2022',
    // The sentences stay readable in the copy.
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: HEADER },
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

export async function main() {
  writeFileSync(PHRASEBOOK_FILE, await renderPhrasebookModule());
  console.log(`wrote ${path.relative(ROOT, PHRASEBOOK_FILE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
