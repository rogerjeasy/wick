/**
 * From measurements to the television's calm points.
 *
 *   npm run calm:build
 *
 * 1. Any raw measurement in .programmes/calm (made by measure.sh, and not
 *    kept in the repository: it is large and has no secrets, only bulk) is
 *    read into scripts/calm-points/measured/<id>.json — the shots, the
 *    fades, the silences and the start of the credits, as numbers.
 * 2. Every measured programme is put through choose.ts, and the result is
 *    written to apps/tv-vega/src/catalog/calmPoints.ts.
 *
 * 3. The break map (page.ts) is written to docs/calm-points/index.html.
 *
 * All three outputs are committed. The second and third are generated,
 * never edited: a test rebuilds each and fails if it differs.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chooseCalmPoints, type CalmPoint, type Measured } from './choose.js';
import { parseSegments, parseSilences, parseSound } from './parse.js';
import { BREAK_MAP_DIR, BREAK_MAP_FILE, DESCRIBED_FILE, programmesForPage, renderBreakMap, type Described } from './page.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
export const MEASURED_DIR = join(HERE, 'measured');
export const CALM_POINTS_FILE = join(ROOT, 'apps', 'tv-vega', 'src', 'catalog', 'calmPoints.ts');
const RAW_DIR = join(ROOT, '.programmes', 'calm');

/** Raw measurements for one programme, as the numbers a calm point is chosen from. */
export function measuredFromRaw(programmeId: string, rekognitionJson: string, silencesText: string): Measured {
  return { programmeId, ...parseSegments(JSON.parse(rekognitionJson)), silences: parseSilences(silencesText), sound: parseSound(silencesText) };
}

export function readMeasured(dir: string = MEASURED_DIR): Measured[] {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .sort()
    .map((file) => JSON.parse(readFileSync(join(dir, file), 'utf8')) as Measured);
}

const literal = (point: CalmPoint): string => `{ atMs: ${point.atMs}, quietMs: ${point.quietMs}, kind: '${point.kind}' }`;

/** The generated module, whole. Pure: the same measurements give the same text. */
export function renderCalmPointsModule(measured: readonly Measured[]): string {
  const programmes = [...measured].sort((a, b) => a.programmeId.localeCompare(b.programmeId));
  const points = programmes.map((m) => {
    const chosen = chooseCalmPoints(m);
    const rows = chosen.map((p) => `    ${literal(p)},\n`).join('');
    return `  '${m.programmeId}': [${chosen.length ? `\n${rows}  ` : ''}],\n`;
  });
  const credits = programmes
    .filter((m) => m.endCreditsMs !== undefined)
    .map((m) => `  '${m.programmeId}': ${m.endCreditsMs},\n`);

  return `/**
 * GENERATED by \`npm run calm:build\` — do not edit.
 *
 * Calm points: the moments inside each programme where a note may arrive
 * without spoiling a scene. Chosen by scripts/calm-points/choose.ts from what
 * was measured on the published encode (scripts/calm-points/measured): the
 * shots, fades and end credits Amazon Rekognition found, and the silences
 * ffmpeg heard. The Natural-Break Engine treats each as a break of a few
 * seconds (break/NaturalBreakEngine.ts).
 */
export interface CalmPoint {
  /** Position in the programme, in milliseconds. */
  readonly atMs: number;
  /** How long the silence around the cut lasts. Zero for a fade through black. */
  readonly quietMs: number;
  readonly kind: 'cut_in_silence' | 'after_black';
}

export const CALM_POINTS: Readonly<Record<string, readonly CalmPoint[]>> = {
${points.join('')}};

/**
 * Where Rekognition says each programme's end credits begin. Not what the
 * player uses — that is the catalogue's own frame-by-frame measurement
 * (catalog.ts creditsPositionMs) — but kept beside it, and held close to it
 * by a test: two measurements made in different ways that agree.
 */
export const DETECTED_END_CREDITS_MS: Readonly<Record<string, number>> = {
${credits.join('')}};
`;
}

export function main(): void {
  mkdirSync(MEASURED_DIR, { recursive: true });
  if (existsSync(RAW_DIR)) {
    for (const file of readdirSync(RAW_DIR).filter((f) => f.endsWith('.rekognition.json'))) {
      const id = file.replace(/\.rekognition\.json$/, '');
      const silences = join(RAW_DIR, `${id}.silences.txt`);
      if (!existsSync(silences)) continue;
      const measured = measuredFromRaw(id, readFileSync(join(RAW_DIR, file), 'utf8'), readFileSync(silences, 'utf8'));
      writeFileSync(join(MEASURED_DIR, `${id}.json`), `${JSON.stringify(measured)}\n`);
      console.log(`${id}: ${measured.shots.length} shots, ${measured.silences.length} silences, ${measured.blackFrames.length} fades`);
    }
  }
  const all = readMeasured();
  writeFileSync(CALM_POINTS_FILE, renderCalmPointsModule(all));
  for (const m of all) console.log(`${m.programmeId}: ${chooseCalmPoints(m).length} calm points`);

  // The page people look at (page.ts), from the same measurements and the sentences on file.
  mkdirSync(BREAK_MAP_DIR, { recursive: true });
  const described = JSON.parse(readFileSync(DESCRIBED_FILE, 'utf8')) as Described;
  writeFileSync(BREAK_MAP_FILE, renderBreakMap(all, programmesForPage(), described));
}
