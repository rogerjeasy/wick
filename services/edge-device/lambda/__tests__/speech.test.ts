/**
 * Read to me — the edge's reading of a card (speech.mjs), without a voice,
 * a bucket or a table: each is handed in.
 *
 * And the edge's copy of the contract (speech.generated.mjs), held to its
 * source byte for byte, as the phrasebook's copy is.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { describe, expect, it, vi } from 'vitest';
import {
  MAX_SPEECH_CHARS as CONTRACT_MAX_CHARS,
  SPEECH_URL_TTL_SEC as CONTRACT_URL_TTL,
  SPEECH_VOICES as CONTRACT_VOICES,
  speechObjectKey as contractSpeechObjectKey,
  speechTextOf as contractSpeechTextOf,
  type Card,
} from '@wick/contracts';
// @ts-expect-error — a plain .mjs script, run by node.
import { SPEECH_FILE, renderSpeechModule } from '../../../../scripts/build-speech.mjs';
// @ts-expect-error — lambda sources are plain .mjs, deployed as-is.
import * as generated from '../speech.generated.mjs';
import {
  MAX_READINGS_AN_HOUR,
  READING_TIME_LIMIT_MS,
  READ_SK_PREFIX,
  answerReading,
  readableCard,
  reachOfferId,
  readingAddress,
  readingClaim,
  readingOf,
  ssmlOf,
  synthesisInput,
  // @ts-expect-error — lambda sources are plain .mjs, deployed as-is.
} from '../speech.mjs';
// @ts-expect-error — lambda sources are plain .mjs, deployed as-is.
import { homeRange } from '../light.mjs';

const base = { householdId: 'hh-1', correlationId: 'c', createdAt: 1 };
const note = { ...base, type: 'MESSAGE', id: 'note-1', fromName: 'Sarah', transcript: 'Ring me tonight, Mum.', suggestedReplies: ['I will', 'Not tonight'], actions: [] } as unknown as Card;
const door = { ...base, type: 'DOOR', id: 'door-1', line: "Someone's at the front door.", description: 'A man holding a parcel.', actions: [{ id: 'dismiss', label: 'Not now', kind: 'dismiss' }] } as unknown as Card;

describe('the edge’s copy of what is read aloud', () => {
  it('is exactly what `npm run speech:build` writes from packages/contracts/src/speech.ts: generated, never edited, never copied by hand', async () => {
    expect(readFileSync(SPEECH_FILE as string, 'utf8')).toBe(await (renderSpeechModule as () => Promise<string>)());
  });

  it('says where it came from, and depends on nothing: the Lambda’s zip is this directory and no more', () => {
    const source = readFileSync(SPEECH_FILE as string, 'utf8');
    expect(source.startsWith('/**\n * GENERATED by `npm run speech:build`')).toBe(true);
    expect(source).toContain('packages/contracts/src/speech.ts');
    expect(source).not.toMatch(/^\s*import\s/m);
    expect(source).not.toMatch(/\brequire\(/);
    expect(Object.keys(generated).sort()).toEqual(['MAX_SPEECH_CHARS', 'SPEECH_URL_TTL_SEC', 'SPEECH_VOICES', 'speechObjectKey', 'speechTextOf']);
  });

  it('answers as the contract’s own does', () => {
    const copy = generated as typeof import('@wick/contracts');
    expect(copy.MAX_SPEECH_CHARS).toBe(CONTRACT_MAX_CHARS);
    expect(copy.SPEECH_URL_TTL_SEC).toBe(CONTRACT_URL_TTL);
    expect(copy.SPEECH_VOICES).toEqual(CONTRACT_VOICES);
    for (const card of [note, door]) expect(copy.speechTextOf(card)).toEqual(contractSpeechTextOf(card));
    const hash = 'a'.repeat(64);
    expect(copy.speechObjectKey('hh-1', hash)).toBe(contractSpeechObjectKey('hh-1', hash));
    expect(() => copy.speechObjectKey('hh-1', '../../snapshots/x')).toThrow();
  });
});

describe('ssmlOf — the passages, a pause between them, and nothing else', () => {
  it('puts the passages in one <speak>, with a 600 ms break between each', () => {
    expect(ssmlOf(['Sarah.', 'Ring me tonight, Mum.', 'I will.'])).toBe('<speak>Sarah.<break time="600ms"/>Ring me tonight, Mum.<break time="600ms"/>I will.</speak>');
    expect(ssmlOf(['Just this.'])).toBe('<speak>Just this.</speak>');
  });

  it('escapes everything a family note can contain: nothing in it is taken for markup', () => {
    expect(ssmlOf(['Tom & I <3 you — "5 > 4", it\'s true.'])).toBe('<speak>Tom &amp; I &lt;3 you — &quot;5 &gt; 4&quot;, it&apos;s true.</speak>');
  });

  it('cannot be broken out of: a note that writes its own SSML is read as the characters it is', () => {
    const ssml = ssmlOf(['Hello</speak><speak><prosody volume="x-loud">LOUD</prosody><audio src="https://evil.example/a.mp3"/>', 'I will.']);

    expect(ssml).toBe(
      '<speak>Hello&lt;/speak&gt;&lt;speak&gt;&lt;prosody volume=&quot;x-loud&quot;&gt;LOUD&lt;/prosody&gt;&lt;audio src=&quot;https://evil.example/a.mp3&quot;/&gt;<break time="600ms"/>I will.</speak>',
    );
    // The only tags in it are ours: one <speak>, its end, and the breaks.
    expect(ssml.match(/<[^>]*>/g)).toEqual(['<speak>', '<break time="600ms"/>', '</speak>']);
  });

  it('leaves out characters XML cannot carry, which would have the whole reading refused', () => {
    expect(ssmlOf(['A\u0000B\u0008C\u000bD\u001fE\tF\nG'])).toBe('<speak>ABCDE\tF\nG</speak>');
  });

  it('is nothing for nothing', () => {
    expect(ssmlOf([])).toBeUndefined();
    expect(ssmlOf(['', '   '])).toBeUndefined();
  });
});

describe('readingOf — what is said, in which voice, and the name it is kept under', () => {
  const english = readingOf({ language: 'en', passages: ['Ring me tonight.', 'I will.'] });

  it('is the household’s language’s one neural voice, from the contract', () => {
    expect(english.voice).toEqual(CONTRACT_VOICES.en);
    expect(readingOf({ language: 'es', passages: ['Llámame.'] }).voice).toEqual(CONTRACT_VOICES.es);
  });

  it('is named by a SHA-256 of the language, the voice and the exact SSML', () => {
    const expected = createHash('sha256').update(`en\n${CONTRACT_VOICES.en.voiceId}\n${english.ssml}`, 'utf8').digest('hex');

    expect(english.hash).toBe(expected);
    expect(english.hash).toMatch(/^[0-9a-f]{64}$/);
    // The contract takes it as the name of the object.
    expect(contractSpeechObjectKey('hh-1', english.hash)).toBe(`tts/hh-1/${english.hash}.mp3`);
  });

  it('changes with the language, with the voice and with the text', () => {
    const same = readingOf({ language: 'en', passages: ['Ring me tonight.', 'I will.'] });
    const otherLanguage = readingOf({ language: 'es', passages: ['Ring me tonight.', 'I will.'] });
    const otherText = readingOf({ language: 'en', passages: ['Ring me tonight.', 'I won’t.'] });
    const otherSplit = readingOf({ language: 'en', passages: ['Ring me tonight. I will.'] });
    const otherVoice = readingOf({ language: 'en', passages: ['Ring me tonight.', 'I will.'], voices: { en: { voiceId: 'Brian', languageCode: 'en-GB' } } });

    expect(same.hash).toBe(english.hash);
    expect(new Set([english.hash, otherLanguage.hash, otherText.hash, otherSplit.hash, otherVoice.hash]).size).toBe(5);
  });

  it('and with nothing else: not the household, not the card, not the time', () => {
    const inputs = [
      { language: 'en', passages: ['Ring me tonight.', 'I will.'], householdId: 'hh-2', cardId: 'note-9', now: 99 },
      { language: 'en', passages: ['Ring me tonight.', 'I will.'], householdId: 'hh-1', cardId: 'note-1', now: 1 },
    ];

    expect(inputs.map((input) => readingOf(input).hash)).toEqual([english.hash, english.hash]);
  });

  it('is nothing when there is nothing to read, or for a language with no voice', () => {
    expect(readingOf({ language: 'en', passages: [] })).toBeUndefined();
    expect(readingOf({ language: 'fr', passages: ['Bonjour.'] })).toBeUndefined();
  });
});

describe('synthesisInput — exactly what Amazon Polly is asked', () => {
  it('is the SSML, in the neural engine, in that voice, as an mp3', () => {
    const reading = readingOf({ language: 'es', passages: ['Llámame esta noche.', 'Lo haré.'] });

    expect(synthesisInput(reading)).toEqual({
      Engine: 'neural',
      OutputFormat: 'mp3',
      TextType: 'ssml',
      Text: '<speak>Llámame esta noche.<break time="600ms"/>Lo haré.</speak>',
      VoiceId: 'Lupe',
      LanguageCode: 'es-US',
    });
  });
});

describe('readingClaim — at most thirty readings a household in an hour', () => {
  const HOUR = 3_600_000;
  const at = 490_000 * HOUR + 1234;
  const claim = readingClaim({ table: 'wick', householdId: 'hh-1', now: at });

  it('counts in one row for the hour, which the table clears away by itself', () => {
    expect(MAX_READINGS_AN_HOUR).toBe(30);
    expect(claim).toEqual({
      TableName: 'wick',
      Key: { pk: { S: 'HH#hh-1' }, sk: { S: `${READ_SK_PREFIX}490000` } },
      UpdateExpression: 'ADD tries :one SET #ttl = :ttl',
      // The thirtieth is counted; the thirty-first is refused.
      ConditionExpression: 'attribute_not_exists(tries) OR tries < :max',
      ExpressionAttributeNames: { '#ttl': 'ttl' },
      ExpressionAttributeValues: { ':one': { N: '1' }, ':max': { N: '30' }, ':ttl': { N: String((490_000 + 2) * 3600) } },
    });
  });

  it('starts again with the next hour', () => {
    expect(readingClaim({ table: 'wick', householdId: 'hh-1', now: at + HOUR }).Key.sk.S).toBe(`${READ_SK_PREFIX}490001`);
    expect(readingClaim({ table: 'wick', householdId: 'hh-1', now: 490_000 * HOUR + HOUR - 1 }).Key.sk.S).toBe(`${READ_SK_PREFIX}490000`);
  });

  it('is kept where nothing that tells the family anything looks: outside the home screen’s rows, and not on the timeline', () => {
    const { ':from': from, ':to': to } = homeRange({ table: 'wick', householdId: 'hh-1' }).ExpressionAttributeValues;
    const sk = claim.Key.sk.S as string;

    expect(sk >= from.S && sk <= to.S).toBe(false);
    expect(sk.startsWith('EVT#')).toBe(false);
    expect(sk.startsWith('CARD#')).toBe(false);
    // And it says nothing of which card, or what was read.
    expect(JSON.stringify(claim)).not.toMatch(/note|card|text/i);
  });
});

describe('readingAddress — a short-lived address for one reading', () => {
  const env = { AWS_ACCESS_KEY_ID: 'test-access-key-id', AWS_SECRET_ACCESS_KEY: 'test/secret+value', AWS_SESSION_TOKEN: 'tok', AWS_REGION: 'us-east-1' };
  const key = `tts/hh-1/${'a'.repeat(64)}.mp3`;

  it('is a presigned GET of that object in the media bucket, good for as long as it takes to play and no longer', () => {
    const url = new URL(readingAddress({ bucket: 'wick-media-1', key, env, now: Date.UTC(2026, 9, 13) }));

    expect(url.host).toBe('wick-media-1.s3.us-east-1.amazonaws.com');
    expect(url.pathname).toBe(`/${key}`);
    expect(url.searchParams.get('X-Amz-Expires')).toBe(String(CONTRACT_URL_TTL));
    expect(CONTRACT_URL_TTL).toBe(300);
    expect(url.searchParams.get('X-Amz-Security-Token')).toBe('tok');
  });

  it('is nothing — never an error — without a bucket or credentials, or for a key that is not a reading’s', () => {
    expect(readingAddress({ bucket: undefined, key, env })).toBeUndefined();
    expect(readingAddress({ bucket: 'b', key, env: {} })).toBeUndefined();
    for (const other of ['snapshots/hh-1/x.jpg', 'tts/../snapshots/x.mp3', 'live/x', '']) expect(readingAddress({ bucket: 'b', key: other, env })).toBeUndefined();
  });
});

describe('readableCard — a stored card that can still be read', () => {
  const queued = { id: 'note-1', urgency: 'DEFERRED', card: note, queuedAt: 2, shownCount: 0 };
  const row = (extra: Record<string, unknown> = {}, card: object = queued) => ({ pk: { S: 'HH#hh-1' }, sk: { S: 'CARD#note-1' }, data: { S: JSON.stringify(card) }, ...extra });

  it('is the card as it is stored', () => {
    expect(readableCard(row(), 10)).toEqual(queued);
  });

  it('is nothing for a card that is not there, has been answered, or has expired', () => {
    expect(readableCard(undefined, 10)).toBeUndefined();
    expect(readableCard({ pk: { S: 'HH#hh-1' }, sk: { S: 'CARD#note-1' } }, 10)).toBeUndefined();
    expect(readableCard(row({ actedAt: { N: '5' } }), 10)).toBeUndefined();
    expect(readableCard(row({ data: { S: 'not json' } }), 10)).toBeUndefined();
    const oldDoor = { id: 'door-1', urgency: 'DOOR', card: door, queuedAt: 1, expiresAt: 300_000, shownCount: 0 };
    expect(readableCard(row({}, oldDoor), 299_999)).toEqual(oldDoor);
    expect(readableCard(row({}, oldDoor), 300_000)).toBeUndefined();
  });
});

