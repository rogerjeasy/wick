describe('answerReading — the address of a reading, or nothing', () => {
  const ADDRESS = 'https://media.example/tts/hh-1/reading.mp3?sig=1';

  function world(over: Record<string, unknown> = {}) {
    const said: Record<string, unknown>[] = [];
    const deps = {
      card: vi.fn(async () => note),
      language: vi.fn(async () => 'en'),
      claim: vi.fn(async () => true),
      kept: vi.fn(async (_key: string) => false),
      synthesize: vi.fn(async (_input: unknown, _signal: AbortSignal) => new Uint8Array([1, 2, 3])),
      keep: vi.fn(async (_key: string, _bytes: Uint8Array, _signal: AbortSignal) => {}),
      address: vi.fn((_key: string) => ADDRESS),
      log: (line: Record<string, unknown>) => { said.push(line); },
      ...over,
    };
    return { deps, said, read: () => answerReading({ householdId: 'hh-1', ...deps }) as Promise<string | undefined> };
  }

  const expectedReading = () => readingOf({ language: 'en', passages: contractSpeechTextOf(note) });

  it('makes the reading once: asks the voice for the card as it is read, keeps it under its hash, and gives its address', async () => {
    const w = world();

    expect(await w.read()).toBe(ADDRESS);

    const reading = expectedReading();
    const key = `tts/hh-1/${reading.hash}.mp3`;
    expect(w.deps.kept).toHaveBeenCalledWith(key);
    expect(w.deps.synthesize.mock.calls.map(([input]) => input)).toEqual([synthesisInput(reading)]);
    expect(w.deps.keep.mock.calls.map(([k, bytes]) => [k, [...bytes]])).toEqual([[key, [1, 2, 3]]]);
    expect(w.deps.address).toHaveBeenCalledWith(key);
    expect(w.said).toEqual([]);
  });

  it('reads what the contract says is read: the sender, the note, and what she can press — in that order', async () => {
    const w = world();

    await w.read();

    expect((w.deps.synthesize.mock.calls[0]![0] as { Text: string }).Text).toBe(
      '<speak>Sarah.<break time="600ms"/>Ring me tonight, Mum.<break time="600ms"/>I will.<break time="600ms"/>Not tonight.</speak>',
    );
  });

  it('does not ask the voice again for a reading it already keeps', async () => {
    const w = world({ kept: vi.fn(async () => true) });

    expect(await w.read()).toBe(ADDRESS);

    expect(w.deps.synthesize).not.toHaveBeenCalled();
    expect(w.deps.keep).not.toHaveBeenCalled();
  });

  it('reads in the household’s voice', async () => {
    const w = world({ language: vi.fn(async () => 'es') });

    await w.read();

    expect(w.deps.synthesize.mock.calls[0]![0]).toMatchObject({ VoiceId: 'Lupe', LanguageCode: 'es-US', Engine: 'neural' });
  });

  describe('gives nothing, and never throws', () => {
    it('for a card that is not there', async () => {
      const w = world({ card: vi.fn(async () => undefined) });

      expect(await w.read()).toBeUndefined();
      expect(w.deps.claim).not.toHaveBeenCalled();
      expect(w.deps.synthesize).not.toHaveBeenCalled();
    });

    it('for a card with nothing to read — and does not count it', async () => {
      const w = world({ card: vi.fn(async () => ({ ...base, type: 'WEEK', id: 'week-1', isoWeek: 'w', text: '  ', actions: [] })) });

      expect(await w.read()).toBeUndefined();
      expect(w.deps.claim).not.toHaveBeenCalled();
    });

    it('past the hour’s thirty — and asks neither the bucket nor the voice', async () => {
      const w = world({ claim: vi.fn(async () => false) });

      expect(await w.read()).toBeUndefined();
      expect(w.deps.kept).not.toHaveBeenCalled();
      expect(w.deps.synthesize).not.toHaveBeenCalled();
      expect(w.said).toEqual([]);
    });

    it('when no address can be signed — before anything is counted or made', async () => {
      const w = world({ address: vi.fn(() => undefined) });

      expect(await w.read()).toBeUndefined();
      expect(w.deps.claim).not.toHaveBeenCalled();
      expect(w.deps.synthesize).not.toHaveBeenCalled();
    });

    const failing = (name: string) => async () => { throw Object.assign(new Error('for note-1: Ring me tonight'), { name }); };

    for (const [what, over] of [
      ['the card cannot be read', { card: vi.fn(failing('ProvisionedThroughputExceededException')) }],
      ['the language cannot be read', { language: vi.fn(failing('InternalServerError')) }],
      ['the count cannot be kept', { claim: vi.fn(failing('InternalServerError')) }],
      ['the voice cannot be loaded or fails', { synthesize: vi.fn(failing('ERR_MODULE_NOT_FOUND')) }],
      ['the voice answers with nothing', { synthesize: vi.fn(async () => new Uint8Array()) }],
      ['the reading cannot be kept', { keep: vi.fn(failing('AccessDenied')) }],
    ] as const) {
      it(`when ${what} — and says why, never what or which`, async () => {
        const w = world(over);

        expect(await w.read()).toBeUndefined();

        expect(w.said).toHaveLength(1);
        expect(w.said[0]).toMatchObject({ level: 'error', msg: 'reading_failed' });
        expect(Object.keys(w.said[0]!).sort()).toEqual(['level', 'msg', 'reason']);
        expect(JSON.stringify(w.said)).not.toMatch(/note-1|Ring me|Sarah|https:|tts\//);
      });
    }

    it('when looking for a kept reading fails, that only means it is made again', async () => {
      const w = world({ kept: vi.fn(failing('AccessDenied')) });

      expect(await w.read()).toBe(ADDRESS);
      expect(w.deps.synthesize).toHaveBeenCalledTimes(1);
    });
  });

  it('gives up at four seconds, tells whatever is under way to stop, and gives nothing', async () => {
    expect(READING_TIME_LIMIT_MS).toBe(4000);
    vi.useFakeTimers();
    try {
      let stopped = false;
      const w = world({
        synthesize: vi.fn((_input: unknown, signal: AbortSignal) => new Promise<Uint8Array>(() => { signal.addEventListener('abort', () => { stopped = true; }); })),
      });
      let answer: string | undefined | 'pending' = 'pending';
      void w.read().then((url) => { answer = url; });

      await vi.advanceTimersByTimeAsync(3999);
      expect(answer).toBe('pending');
      await vi.advanceTimersByTimeAsync(1);
      expect(answer).toBeUndefined();
      expect(stopped).toBe(true);
      expect(w.said).toEqual([{ level: 'error', msg: 'reading_failed', reason: 'timeout' }]);
    } finally {
      vi.useRealTimers();
    }
  });
});
