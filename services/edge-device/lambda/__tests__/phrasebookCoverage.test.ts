const LONDON = 'Europe/London';
/** Monday 12 October 2026, 10:30 in London (BST). */
const NOW = Date.UTC(2026, 9, 12, 9, 30);
const HOUR = 3_600_000;

const labels = (card: { readonly actions: readonly { readonly label: string }[] }): string[] => card.actions.map((a) => a.label);
const cardOf = <T extends Card['type']>(queued: QueuedCard | undefined, type: T): Extract<Card, { type: T }> => {
  if (queued?.card.type !== type) throw new Error(`not a ${type} card`);
  return queued.card as Extract<Card, { type: T }>;
};

const member = (userId: string, name: string, role = 'family', requestedAt = 1) => ({
  pk: { S: 'HH#margaret' },
  sk: { S: `MEM#${userId}` },
  name: { S: name },
  role: { S: role },
  status: { S: 'allowed' },
  requestedAt: { N: String(requestedAt) },
});
const look = (userId: string, name: string, at: number) => ({ pk: { S: 'HH#margaret' }, sk: { S: `LOOKIN#${userId}` }, name: { S: name }, lookedAt: { N: String(at) } });
const light = (outAt?: number) => ({ pk: { S: 'HH#margaret' }, sk: { S: 'LIGHT' }, ...(outAt === undefined ? {} : { outAt: { N: String(outAt) } }) });
const meta = { pk: { S: 'HH#margaret' }, sk: { S: 'META' } };

describe('the edge’s copy of the phrasebook', () => {
  it('is exactly what `npm run phrasebook:build` writes from packages/contracts/src/phrasebook: generated, never edited', async () => {
    expect(readFileSync(PHRASEBOOK_FILE as string, 'utf8')).toBe(await (renderPhrasebookModule as () => Promise<string>)());
  });

  it('says where it came from, and depends on nothing: the Lambda’s zip is this directory and no more', () => {
    const source = readFileSync(PHRASEBOOK_FILE as string, 'utf8');
    expect(source.startsWith('/**\n * GENERATED by `npm run phrasebook:build`')).toBe(true);
    expect(source).toContain('packages/contracts/src/phrasebook');
    expect(source).not.toMatch(/^\s*import\s/m);
    expect(source).not.toMatch(/\brequire\(/);
    expect(Object.keys(generated).sort()).toEqual(['cardIn', 'freeTextOf', 'homeIn', 'patchIn', 'sayIn']);
  });

  it('answers as the contracts’ own does, for every sentence in the catalogue', () => {
    const filled = Object.values(ES_CATALOGUE)
      .flat()
      .map((entry) =>
        entry.en
          .replace(/\{(first|name|names)\d?\}/g, 'Anne-Marie')
          .replace(/\{title\}/g, 'Tears of Steel')
          .replace(/\{day\d?\}/g, 'Saturday')
          .replace(/\{date\}/g, 'Saturday 31 January')
          .replace(/\{time\d?\}/g, '1:05 pm')
          .replace(/\{part\}/g, 'this evening')
          .replace(/\{parts\}/g, 'evenings')
          .replace(/\{n\d?\}/g, '4'),
      );
    expect(filled.length).toBeGreaterThan(120);
    for (const english of [...filled, 'A sentence Wick has never said.', '']) {
      expect(sayIn('es', english), english).toBe(contractSayIn('es', english));
      if (english) expect(sayIn('es', english), english).not.toBe(english);
    }
  });
});

describe('the Light card (light.mjs)', () => {
  const lightCard = (items: object[], now = NOW): LightCard => coverage.spanish(cardOf(buildLightCard({ householdId: 'margaret', items, now, timeZone: LONDON }) as QueuedCard, 'LIGHT'));

  it('on, with the one person who can see it', () => {
    const card = lightCard([member('u_sarah', 'Sarah Hughes'), meta]);
    expect(card).toMatchObject({
      headline: 'Su luz está encendida.',
      detail: 'Sarah puede ver que su día ha empezado, y nada más: ni cuándo, ni lo que usted ve.',
    });
    expect(labels(card)).toEqual(['Dejarla encendida', 'Apagarla por hoy']);
  });

  it('out for today, in words that do not say why', () => {
    const card = lightCard([light(NOW - HOUR), member('u_sarah', 'Sarah Hughes'), meta]);
    expect(card).toMatchObject({
      headline: 'Su luz está apagada por hoy.',
      detail: 'Sarah no puede saber si usted la apagó o si todavía no se ha encendido. Mañana se enciende de nuevo.',
    });
    expect(labels(card)).toEqual(['Dejarla apagada', 'Encenderla de nuevo']);
  });

  it('speaks of her family when several can see it, and never counts a neighbour among them', () => {
    const several = [member('u_sarah', 'Sarah'), member('u_david', 'David'), member('u_tom', 'Tom', 'neighbour'), meta];
    expect(lightCard(several).detail).toBe('Su familia puede ver que su día ha empezado, y nada más: ni cuándo, ni lo que usted ve.');
    expect(lightCard([light(NOW - HOUR), ...several]).detail).toBe('Su familia no puede saber si usted la apagó o si todavía no se ha encendido. Mañana se enciende de nuevo.');
  });

  it('adds who looked in today: in the morning, the afternoon and the evening', () => {
    const sarah = member('u_sarah', 'Sarah Hughes');
    const said = (lookedAt: number, now: number, out = false): string => lightCard([...(out ? [light(now - 60_000)] : []), look('u_sarah', 'Sarah Hughes', lookedAt), sarah, meta], now).detail;

    expect(said(NOW - HOUR, NOW)).toBe('Sarah puede ver que su día ha empezado, y nada más: ni cuándo, ni lo que usted ve. Sarah ha preguntado por usted esta mañana.');
    expect(said(NOW + 4 * HOUR, NOW + 5 * HOUR)).toBe('Sarah puede ver que su día ha empezado, y nada más: ni cuándo, ni lo que usted ve. Sarah ha preguntado por usted esta tarde.');
    expect(said(NOW + 9 * HOUR, NOW + 10 * HOUR)).toBe('Sarah puede ver que su día ha empezado, y nada más: ni cuándo, ni lo que usted ve. Sarah ha preguntado por usted esta noche.');
    expect(said(NOW - HOUR, NOW, true)).toBe(
      'Sarah no puede saber si usted la apagó o si todavía no se ha encendido. Mañana se enciende de nuevo. Sarah ha preguntado por usted esta mañana.',
    );
  });

  it('whatever the people are called, and never past the card', () => {
    for (const name of ['Anne-Marie', 'O’Brien', "D'Arcy", 'José', 'Bartholomew-Fitzgerald24']) {
      for (const out of [false, true]) {
        const card = lightCard([...(out ? [light(NOW - 60_000)] : []), look('u_1', `${name} Smith`, NOW - HOUR), member('u_1', `${name} Smith`), meta]);
        expect(card.detail.startsWith(`${name} `), card.detail).toBe(true);
        expect(card.detail.endsWith(`${name} ha preguntado por usted esta mañana.`), card.detail).toBe(true);
        expect(card.detail.length, card.detail).toBeLessThanOrEqual(MAX_CARD_DETAIL_CHARS);
      }
    }
  });

  it('the home screen is told who looked in, in her language, and nothing else of it changes', () => {
    const english = homeState({ items: [look('u_sarah', 'Sarah Hughes', NOW - HOUR), member('u_sarah', 'Sarah Hughes'), meta], now: NOW, timeZone: LONDON });
    expect(english.lookedIn.line).toBe('Sarah looked in this morning.');
    expect(homeIn('es', english)).toEqual({ ...english, lookedIn: { ...english.lookedIn, line: 'Sarah ha preguntado por usted esta mañana.' } });
  });

  it('a press on the card in her language is the press it always was', () => {
    const on = lightCard([member('u_sarah', 'Sarah'), meta]);
    expect(on.actions.map((a) => a.id)).toEqual([LIGHT_ACTIONS.ok, LIGHT_ACTIONS.putOut]);
    expect(lightPress(on.id, on.actions[1]!.id)).toBe(LIGHT_ACTIONS.putOut);
    const out = lightCard([light(NOW - HOUR), member('u_sarah', 'Sarah'), meta]);
    expect(lightPress(out.id, out.actions[1]!.id)).toBe(LIGHT_ACTIONS.lightAgain);
  });
});

describe('"What Sarah sees" (sharing.mjs)', () => {
  const NEVER = 'Nunca se comparte, elija lo que elija: su salud, su dinero, sus relaciones, adónde va ni sus palabras.';
  const page = (index: number, over: { exclusions?: string[]; watchers?: string[]; familyName?: string } = {}): SharingCard =>
    coverage.spanish(cardOf(buildSharingCard({ householdId: 'margaret', page: index, policyJson: undefined, exclusions: over.exclusions ?? [], now: NOW, ...over }) as QueuedCard, 'SHARING'));

  it('one page for each thing the family can see, in plain words', () => {
    expect([0, 1, 2, 3].map((i) => page(i, { watchers: ['Sarah'] }).headline)).toEqual([
      'Cuando alguien viene a su puerta de entrada.',
      'Quién viene de visita, por su nombre, como Maria.',
      'Un breve resumen de su semana.',
      'Sus citas, en resumen.',
    ]);
    expect([0, 1, 2, 3].map((i) => page(i, { watchers: ['Sarah'] }).detail)).toEqual([1, 2, 3, 4].map((n) => `${n} de 4. Sarah puede ver esto. ${NEVER}`));
    expect(labels(page(0, { watchers: ['Sarah'] }))).toEqual(['Mantener en privado', 'Siguiente', 'Listo']);
  });

  it('says so when she is keeping it private, and offers to share it again', () => {
    const card = page(1, { exclusions: ['PRESENCE'], watchers: ['Sarah'] });
    expect(card.detail).toBe(`2 de 4. Usted mantiene esto en privado. ${NEVER}`);
    expect(labels(card)).toEqual(['Compartir de nuevo', 'Siguiente', 'Listo']);
  });

  it('says who can see it: one person by name, her family, or nobody yet', () => {
    expect(page(0, { watchers: allowedFirstNames([member('u_1', 'Anne-Marie O’Brien')]) as string[] }).detail).toBe(`1 de 4. Anne-Marie puede ver esto. ${NEVER}`);
    expect(page(0, { watchers: ['Sarah', 'David'] }).detail).toBe(`1 de 4. Su familia puede ver esto. ${NEVER}`);
    expect(page(0, { watchers: [] }).detail).toBe(`1 de 4. Todavía nadie puede ver esto: usted no ha aceptado a nadie. ${NEVER}`);
    expect(page(0, { familyName: 'José' }).detail).toBe(`1 de 4. José puede ver esto. ${NEVER}`);
    expect(page(0).detail).toBe(`1 de 4. Su familia puede ver esto. ${NEVER}`);
  });

  it('every page in every state fits the card, with a name of twenty-four characters', () => {
    for (let i = 0; i < 4; i += 1) {
      for (const over of [{ watchers: ['Bartholomew-Fitzgerald24'] }, { watchers: [] }, { exclusions: ['DOOR_EVENT', 'PRESENCE', 'RHYTHM', 'COMMITMENT'] }, {}]) {
        expect(page(i, over).detail.length).toBeLessThanOrEqual(MAX_CARD_DETAIL_CHARS);
      }
    }
  });

  it('a press on the card in her language is the press it always was', () => {
    const card = page(1, { watchers: ['Sarah'] });
    expect(card.actions.map((a) => a.id)).toEqual([SHARING_ACTIONS.toggle, SHARING_ACTIONS.next, SHARING_ACTIONS.done]);
    expect(sharingStep({ card }, card.actions[0]!.id, [])).toEqual({ page: 1, set: { factClass: 'PRESENCE', keepPrivate: true } });
    expect(sharingStep({ card }, card.actions[1]!.id, [])).toEqual({ page: 2 });
  });
});

describe('the offer to ask someone to ring (reach.mjs)', () => {
  const offer = (items: object[]): ReachCard => coverage.spanish(cardOf(buildReachAskCard({ householdId: 'margaret', reachId: String(NOW), first: firstToAsk(items), now: NOW }) as QueuedCard, 'REACH'));

  it('names the first person in her circle, and says what Wick does not do', () => {
    const card = offer([member('u_david', 'David', 'family', 2), member('u_sarah', 'Sarah Hughes', 'organiser', 5), member('u_tom', 'Tom', 'neighbour', 1)]);
    expect(card).toMatchObject({
      headline: '¿Pedir a Sarah que le llame?',
      detail: 'A Sarah solo se le dirá que usted desea una llamada. Wick no llama para pedir ayuda: en una emergencia, use el teléfono.',
    });
    expect(labels(card)).toEqual(['Sí, pedírselo a Sarah', 'Solo saludar', 'No, ahora no']);
    expect(card.actions.map((a) => reachKindOf(a.id))).toEqual(['ring', 'hello', undefined]);
    expect(card.actions.map((a) => a.id)).toEqual([REACH_ACTIONS.ring, REACH_ACTIONS.hello, REACH_ACTIONS.notNow]);
  });

  it('whatever that person is called', () => {
    for (const name of ['Anne-Marie', 'O’Brien', 'José', 'Bartholomew-Fitzgerald24']) {
      const card = offer([member('u_1', `${name} Smith`)]);
      expect(card.headline).toBe(`¿Pedir a ${name} que le llame?`);
      expect(card.detail!.length).toBeLessThanOrEqual(MAX_CARD_DETAIL_CHARS);
    }
  });

  it('says so when there is nobody to ask', () => {
    const card = offer([]);
    expect(card).toMatchObject({
      headline: 'Ahora mismo no hay nadie a quien Wick pueda pedírselo.',
      detail: 'Cuando haya aceptado a alguien en su círculo familiar, podrá pedirle aquí que le llame.',
    });
    expect(labels(card)).toEqual(['De acuerdo']);
  });
});

describe('the question at the credits (watch-together.mjs)', () => {
  const session = (over: Record<string, { S: string }> = {}) => ({ sessionId: { S: 's-1' }, programmeTitle: { S: 'Tears of Steel' }, invitedByName: { S: 'Sarah' }, ...over });
  const question = (item: object): WatchCard => coverage.spanish(cardOf(buildQuestionCard({ householdId: 'margaret', item, now: NOW }) as QueuedCard, 'WATCH'));

  it('names the film and who it was watched with, and offers her three answers', () => {
    const card = question(session());
    expect(card).toMatchObject({ withName: 'Sarah', headline: 'Ha terminado Tears of Steel, con Sarah.', detail: '¿Qué le pareció?' });
    expect(labels(card)).toEqual(['Me encantó.', 'Estuvo bien.', 'No fue muy de mi gusto.']);
  });

  it('for every film and any name, and when the row has lost either', () => {
    expect(question(session({ programmeTitle: { S: 'Big Buck Bunny' }, invitedByName: { S: 'Anne-Marie' } })).headline).toBe('Ha terminado Big Buck Bunny, con Anne-Marie.');
    expect(question(session({ programmeTitle: { S: 'Sintel' }, invitedByName: { S: 'José' } })).headline).toBe('Ha terminado Sintel, con José.');
    expect(question({ sessionId: { S: 's-1' } }).headline).toBe('Ha terminado la película, con su familia.');
  });

  it('a press on the card in her language is the answer it always was', () => {
    const card = question(session());
    expect(card.actions.map((a) => a.id)).toEqual(Object.keys(WATCH_ANSWERS));
    expect(card.actions.map((a) => watchPress(card.id, a.id))).toEqual(Object.keys(WATCH_ANSWERS).map((answer) => ({ sessionId: 's-1', press: 'answer', answer })));
  });
});

describe('a picture that was not put away (mantel.mjs cardBack, sent by device-event.mjs notPutAway)', () => {
  /** The picture's card as the server stored it (mcp-server photos/send.ts buildPhotoCard): the contracts' words, and no address. */
  const storedRow = (fromName: string) => {
    const card: PhotoCard = { type: 'PHOTO', id: photoCardId('p_8Jk2-xQ9a'), householdId: 'margaret', correlationId: photoCardId('p_8Jk2-xQ9a'), createdAt: NOW, photoId: 'p_8Jk2-xQ9a', fromName, ...photoCardWords(fromName) };
    return { data: { S: JSON.stringify({ id: card.id, urgency: 'DEFERRED', queuedAt: NOW, shownCount: 1, card }) } };
  };
  const back = (fromName: string, full: boolean): PhotoCard => {
    const stored = storedPhotoCard(storedRow(fromName), 'p_8Jk2-xQ9a') as { queued: QueuedCard };
    return coverage.spanish(cardOf(cardBack(stored.queued, { full }) as QueuedCard, 'PHOTO'));
  };

  it('the sentence the edge writes is the very one the phrasebook holds', () => {
    expect(MANTEL_FULL_NOTICE).toBe(CONTRACT_FULL_NOTICE);
    expect(Object.values(ES_CATALOGUE).flat().map((entry) => entry.en)).toContain(MANTEL_FULL_NOTICE);
    expect(sayIn('es', MANTEL_FULL_NOTICE)).toBe('Su repisa está llena. Quite una foto, y entonces podrá guardar esta.');
  });

  it('goes back saying her mantelpiece is full, and what to do', () => {
    const card = back('Sarah Hughes', true);
    expect(card).toMatchObject({
      photoId: 'p_8Jk2-xQ9a',
      fromName: 'Sarah Hughes',
      headline: 'Una foto de parte de Sarah.',
      notice: 'Su repisa está llena. Quite una foto, y entonces podrá guardar esta.',
    });
    expect(labels(card)).toEqual(['Guardarla', 'Gracias']);
    expect(card.notice!.length).toBeLessThanOrEqual(MAX_CARD_DETAIL_CHARS);
  });

  it('goes back without a word when the keeping simply failed', () => {
    const card = back('Anne-Marie O’Brien', false);
    expect(card.headline).toBe('Una foto de parte de Anne-Marie.');
    expect(card).not.toHaveProperty('notice');
    expect(labels(card)).toEqual(['Guardarla', 'Gracias']);
  });

  it('a press on the card in her language is the press it always was', () => {
    const card = back('Sarah Hughes', true);
    expect(card.actions.map((a) => a.id)).toEqual([PHOTO_ACTIONS.keep, PHOTO_ACTIONS.thanks]);
    expect(card.actions.map((a) => photoPress(card.id, a.id))).toEqual([
      { photoId: 'p_8Jk2-xQ9a', answer: 'keep' },
      { photoId: 'p_8Jk2-xQ9a', answer: 'thanks' },
    ]);
  });
});

describe('her answer on a card the edge did not write', () => {
  const base = { householdId: 'margaret', correlationId: 'c-1', createdAt: NOW };

  it('the Circle card (circle.mjs): the press still names the person, and still means allow or not', () => {
    const english: CircleCard = {
      ...base,
      type: 'CIRCLE',
      id: circleCardId('u_sarah'),
      personName: 'Sarah Hughes',
      role: 'family',
      headline: 'Sarah Hughes would like to join your family circle.',
      detail: 'If you allow it, Sarah can send you notes here and see what you choose to share. You can change what is shared at any time.',
      actions: [
        { id: CIRCLE_ACTIONS.allow, label: 'Allow Sarah', kind: 'primary' },
        { id: CIRCLE_ACTIONS.decline, label: 'No, thank you', kind: 'secondary' },
      ],
    };
    const card = cardIn('es', english) as CircleCard;
    expect(card).toEqual(contractCardIn('es', english));
    expect(labels(card)).toEqual(['Aceptar a Sarah', 'No, gracias']);
    expect(circleDecision(card.id, card.actions[0]!.id)).toEqual({ userId: 'u_sarah', status: 'allowed' });
    expect(circleDecision(card.id, card.actions[1]!.id)).toEqual({ userId: 'u_sarah', status: 'declined' });
  });

  it('a note (note-reply.mjs): she reads the reply in her language, and the family is told the words that were stored', () => {
    const english: MessageCard = { ...base, type: 'MESSAGE', id: 'note-1f0c', actions: [], fromName: 'Sarah', transcript: 'Shall I come on Saturday?', suggestedReplies: ['Yes, please do.', 'Another day would be better.', 'Not right now.'] };
    const stored = { data: { S: JSON.stringify({ id: english.id, card: english }) } };

    const card = cardIn('es', english) as MessageCard;
    expect(card.suggestedReplies).toEqual(['Sí, por favor.', 'Mejor otro día.', 'Ahora mismo no.']);
    expect(freeTextOf(english)).toEqual({ transcript: 'Shall I come on Saturday?' });
    // She presses the second button; what travels back is which button, and the words are the server's own stored English.
    const index = replyIndex(card.id, 'reply_1');
    expect(index).toBe(1);
    expect(replyText(stored, index)).toBe('Another day would be better.');
  });
});

